"""Orchestration of the `exits` command: parse, pair, check, choose arrival directions, build the link file.
Pure functions over text + manifest + an optional exits_geom.World, so it is testable without the game."""

from __future__ import annotations

from .exits import (FORMAT, STEP_M, Exit, Side, check_exit, is_duplicate_of, link_ids, make_link, open_side,
                    pair_exits, parse_area_bbox, parse_exit_locs, prior_interior, prior_outdoor, scene_pockets,
                    trigger_conflicts)

NOTE = ("GENERATED by `python3 -m tools.importers exits` from Config/dat/ExitLocs.dat + areabbox.dat (own install, "
        "derived data: stays under imported/, never committed). Same format and units as tools/ue/door_links.json "
        "(UE cm / UE yaw degrees; UE = (100x, -100y, 100z)). The two hand-made main-door links stay authoritative: a "
        "generated pair that duplicates them is skipped. 'exit' is 2.5 m (less in cramped rooms) from the trigger on "
        "the arrival side; z is a hint, the runtime floor-snaps.")


def choose_side(e: Exit, boxes, world, step=STEP_M) -> Side:
    """Arrival direction for one side of a link (see the heuristic in exits.py's docstring)."""
    box = boxes.get(e.akey)
    outdoor = e.akey == "mainmap"
    prior, why = None, ""
    if outdoor:
        if world is not None:
            prior = prior_outdoor(e, world.solids(e.x, e.y, e.z))
            why = "away from nearby buildings"
            if prior is None:
                prior = open_side(e, world.rects(e.x, e.y))
                why = "toward the open side"
    else:
        prior = prior_interior(e, box)
        why = "toward the area box centre"
    side = Side(e, prior or (1.0, 0.0), f"prior {why or 'default +x'} (no geometry check)", arrive_dist=step)
    if world is None:
        return side
    local = world.local(e.x, e.y, e.z)
    if local.n == 0:
        side.warnings.append("no imported geometry near the exit point")
        side.method = f"prior {why} (no geometry near the point)"
        return side
    res = local.choose((e.x, e.y), e.z, prior, want_open=outdoor)
    side.floor_z = res["floor_z"]
    if side.floor_z is None:
        side.warnings.append("no floor under the exit point within -1.6..+1.0 m of its listed z")
    elif abs(side.floor_z - e.z) > 1.0:
        side.warnings.append(f"floor under the exit point is z={side.floor_z:.2f}, listed z={e.z:.2f}")
    runs = " ".join(f"{k}{v:.1f}" for k, v in res["runs"].items())
    encl = " ".join(f"{k}{v:.1f}" for k, v in res["enclosure"].items())
    if res["ok"]:
        side.direction = res["direction"]
        run = res["runs"][res["name"]]
        side.arrive_dist = min(step, max(1.0, run - 0.4))
        side.method = (f"geometry {res['name']} (clear runs m: {runs}; walled-in: {encl}; "
                       f"{'wall/void behind' if res['back_blocked'] else 'open behind'}; prior {why})")
        ref = side.floor_z if side.floor_z is not None else e.z
        side.arrive_z = local.floor_z(e.x + side.direction[0] * side.arrive_dist,
                                      e.y + side.direction[1] * side.arrive_dist, ref)
        if not res["confident"]:
            side.warnings.append("facing uncertain: the two sides of the door look alike to the geometry check "
                                 "(arrival may be on the building side); check the preview / in engine")
        if side.arrive_dist < step - 1e-6:
            side.warnings.append(f"cramped: arrival only {side.arrive_dist:.1f} m from the trigger")
    else:
        side.method = f"prior {why} (geometry found no clear run: {runs})"
        side.warnings.append(f"no clear walkable run from the exit point in any direction (runs m: {runs}); "
                             "direction is the heuristic prior, verify in engine")
    return side


def build(exits_text, bbox_text, manifest=None, handmade=None, world=None, step=STEP_M):
    """Parse, pair, check and build. -> (links_doc, report dict, sides dict link-id -> Side)."""
    exits, parse_warn = parse_exit_locs(exits_text)
    boxes = parse_area_bbox(bbox_text)
    pairs, unpaired = pair_exits(exits, boxes)
    pockets = scene_pockets(manifest, world.scene_extents() if world is not None else None) if manifest else []
    handmade = handmade or []
    checks: dict[str, dict] = {}

    def chk(e):
        k = f"{e.area}#{e.exit_id}@L{e.line}"
        if k not in checks:
            c = check_exit(e, boxes, pockets)
            if not manifest:
                c["problems"] = [p for p in c["problems"] if "imported" not in p and "covers this area" not in p]
                c["in_pocket"] = None
            checks[k] = c
        return checks[k]

    ids = link_ids(pairs)
    links, rejected, skipped, sides = [], [], [], {}
    for p, (ida, idb) in zip(pairs, ids):
        ca, cb = chk(p.a), chk(p.b)
        reasons = [f"{e.ref}: {m}" for e, c in ((p.a, ca), (p.b, cb)) for m in c["problems"]]
        if reasons:
            rejected.append({"pair": [p.a.ref, p.b.ref], "kind": p.kind, "reasons": reasons,
                             "a": [p.a.x, p.a.y, p.a.z], "b": [p.b.x, p.b.y, p.b.z]})
            continue
        sa = choose_side(p.a, boxes, world, step)
        sb = choose_side(p.b, boxes, world, step)
        la = make_link(sa, sb, ida, idb, f"{p.a.area} exit {p.a.exit_id} to {p.b.area} (ExitLocs.dat)")
        lb = make_link(sb, sa, idb, ida, f"{p.b.area} exit {p.b.exit_id} to {p.a.area} (ExitLocs.dat)")
        dup = is_duplicate_of(la, handmade) or is_duplicate_of(lb, handmade)
        if dup:
            skipped.append({"pair": [ida, idb], "duplicates": dup, "exits": [p.a.ref, p.b.ref]})
            continue
        links += [la, lb]
        sides[ida], sides[idb] = sa, sb

    overlaps, arrivals = trigger_conflicts(links + list(handmade))
    doc = {"_owner": "tools.importers exits (generated)", "_format": FORMAT, "_note": NOTE, "links": links}
    counts = {"outdoor-interior": sum(p.kind == "outdoor-interior" for p in pairs),
              "interior-interior": sum(p.kind == "interior-interior" for p in pairs), "total": len(pairs)}
    report = {
        "exits_total": len(exits), "exits_live": sum(1 for e in exits if not e.disabled),
        "pairs": [{"a": p.a.ref, "b": p.b.ref, "kind": p.kind} for p in pairs],
        "pair_counts": counts,
        "emitted_links": len(links), "emitted_pairs": len(links) // 2,
        "skipped_duplicates_of_handmade": skipped,
        "rejected_pairs": rejected,
        "unpaired": [{"exit": e.ref, "dest": e.dest, "xyz": [e.x, e.y, e.z], "reason": r} for e, r in unpaired],
        "parse_warnings": parse_warn,
        "exit_checks": checks,
        "trigger_overlaps": overlaps,
        "arrival_inside_other_trigger": arrivals,
        "link_warnings": {l["id"]: l["warnings"] for l in links if l.get("warnings")},
        "geometry": world is not None,
    }
    return doc, report, sides


def format_report(report):
    c = report["pair_counts"]
    out = [f"exits: {report['exits_live']} live rows ({report['exits_total']} incl. commented out)",
           f"pairs: {c['total']} (outdoor<->interior {c['outdoor-interior']}, interior<->interior {c['interior-interior']}); "
           f"emitted {report['emitted_pairs']} pairs / {report['emitted_links']} links; "
           f"duplicates of the hand-made links skipped: {len(report['skipped_duplicates_of_handmade'])}; "
           f"rejected (exit point misses box/pocket): {len(report['rejected_pairs'])}; geometry check: {report['geometry']}"]
    for s in report["skipped_duplicates_of_handmade"]:
        out.append(f"  skipped {s['exits'][0]} <-> {s['exits'][1]} (= hand-made {s['duplicates']})")
    if report["rejected_pairs"]:
        out.append("rejected pairs:")
        for r in report["rejected_pairs"]:
            out.append(f"  {r['pair'][0]} <-> {r['pair'][1]}")
            for m in r["reasons"]:
                out.append(f"      {m}")
    if report["unpaired"]:
        out.append(f"unpaired exits ({len(report['unpaired'])}):")
        for u in report["unpaired"]:
            out.append(f"  {u['exit']:<28} -> {str(u['dest']):<18} {u['reason']}")
    for w in report["parse_warnings"]:
        out.append(f"parse warning: {w}")
    if report["trigger_overlaps"]:
        out.append("overlapping trigger boxes: " + ", ".join(f"{a}/{b}" for a, b in report["trigger_overlaps"]))
    if report["arrival_inside_other_trigger"]:
        out.append("arrival point inside another trigger: " +
                   ", ".join(f"{a} in {b}" for a, b in report["arrival_inside_other_trigger"]))
    for k, v in report["link_warnings"].items():
        out.append(f"warning {k}: " + "; ".join(v))
    return "\n".join(out)
